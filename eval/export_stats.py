"""Export all aggregated statistics behind the paper's tables/figures into
data/ as CSV/JSON (an archival, self-contained
snapshot). The figures/tables themselves are generated by figures/make_nmi_figures.py,
which reads the raw diagnosed details from data/results/ + se_results/ (NOT this folder).

Run: MOLREHALLU_REGEN=1 python eval/export_stats.py
"""
import csv
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import metrics as MX  # noqa: E402

OUT = os.path.join(MX.BASE, "data")

# Guard: this script OVERWRITES data/*.csv in place from data/results/, and the public release
# ships only a small subset of the diagnosed results tree. Run against that subset it would
# silently replace the submitted per-model statistics with one model's worth of numbers.
# It also writes at import time, so `import export_stats` alone is destructive.
if os.environ.get("MOLREHALLU_REGEN") != "1":
    raise SystemExit(
        "export_stats.py overwrites data/*.csv from the full diagnosed results tree, which is "
        "not part of the public release. Refusing to run so the shipped statistics are not "
        "replaced with incomplete data. Set MOLREHALLU_REGEN=1 to override."
    )

os.makedirs(OUT, exist_ok=True)

GEN = ["cap2mol", "mol2cap", "retrosynthesis"]
CLS = ["bace", "bbbp", "hiv", "tox21", "clintox"]
ALL_TASKS = GEN + MX.S2 + CLS
# every model with a results/ directory
MODELS = sorted(os.path.basename(os.path.dirname(p))
                for p in glob.glob(f"{MX.BASE}/data/results/*/") )
MODELS = sorted({os.path.basename(p.rstrip("/")) for p in glob.glob(f"{MX.BASE}/data/results/*/")})

FIELDS = ["n", "perf", "perf_er0", "perf_erpos", "pct_er0", "overall",
          "IR", "IO", "ER", "EO", "gc", "cp", "length", "info", "validity", "tanimoto"]


def se(model, task):
    p = f"{MX.BASE}/se_results/{model}/{task}/se_summary.json"
    if os.path.exists(p):
        try:
            return json.load(open(p)).get("semantic_entropy", {}).get("mean")
        except Exception:
            return None
    return None


def rnd(v, n=4):
    return round(v, n) if isinstance(v, (int, float)) else v


# ---- 1. per-(model, task) full stats ---------------------------------------
with open(f"{OUT}/stats_per_model_task.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["model", "task"] + FIELDS + ["semantic_entropy"])
    for m in MODELS:
        for t in ALL_TASKS:
            s = MX.task_stats(m, t)
            if not s:
                continue
            w.writerow([m, t] + [rnd(s.get(k)) for k in FIELDS] + [rnd(se(m, t))])

# ---- 2. per-(model, family) aggregates incl. decoupling gap ----------------
with open(f"{OUT}/stats_per_family.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["model", "family", "n", "perf", "perf_er0", "perf_erpos",
                "decoupling_gap", "pct_er0", "overall", "ER", "EO", "IR", "IO",
                "gc", "cp", "length"])
    for m in MODELS:
        for fam, ts in MX.FAMILIES:
            s = MX.family_stats(m, ts)
            if not s:
                continue
            gap = (s["perf_er0"] - s["perf_erpos"]) if (s["perf_er0"] is not None and s["perf_erpos"] is not None) else None
            w.writerow([m, fam, s["n"], rnd(s["perf"]), rnd(s["perf_er0"]), rnd(s["perf_erpos"]),
                        rnd(gap), rnd(s["pct_er0"]), rnd(s["overall"]), rnd(s["ER"]), rnd(s["EO"]),
                        rnd(s["IR"]), rnd(s["IO"]), rnd(s["gc"]), rnd(s["cp"]), rnd(s["length"])])

# ---- 3. mitigation comparison (baseline / process / Chem-R-Faithful) -----------------
MIT = [("Chem-R", "baseline"), ("Chem-R-Faithful", "coupled")]
with open(f"{OUT}/mitigation.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["family", "variant", "perf", "ER", "pct_er0", "decoupling_gap", "overall", "cp", "gc"])
    for fam, ts in MX.FAMILIES:
        for mid, lab in MIT:
            s = MX.family_stats(mid, ts)
            if not s:
                continue
            gap = (s["perf_er0"] - s["perf_erpos"]) if (s["perf_er0"] is not None and s["perf_erpos"] is not None) else None
            w.writerow([fam, lab, rnd(s["perf"]), rnd(s["ER"]), rnd(s["pct_er0"]),
                        rnd(gap), rnd(s["overall"]), rnd(s["cp"]), rnd(s["gc"])])

# ---- 4. attention / perturbation summary (if the run is present) -----------
# CONVENTIONS (must match methods.tex "Attention attribution"):
#   * LAYER: every attention statistic is read at the MIDDLE layer l*=floor(L/2).
#     The attn_in_fg / attn_cot_fg / pertok / raw lists are stored per layer, so
#     we index [L//2] rather than averaging over layers. The first layer is the
#     near-uniform attention-sink regime and the final layers do local next-token
#     copying; averaging all layers dilutes the answer->source signal with both.
#   * SCOPE: the matched-token control and the causal perturbation are reported on
#     cap2mol only -- the natural-language-input task where a functional-group word
#     is named in the input (so the input-corruption control is defined) and where
#     the paper frames the mechanism. (region_attr, used for Fig 6, is full-volume
#     across all tasks and is exported separately by eval/pull_fullvol.py.)
import numpy as np  # noqa: E402
CAP = {"cap2mol"}
def _mid(lst):
    """middle-layer value of a per-layer attention list."""
    return lst[len(lst) // 2] if lst else None
attn_rows = []
# Only region_*.json carry `perturb`/`matched`/`attn`; globbing all of data/raw/ would emit a
# junk row per drift_/condsent_/gradattr_ file. Take the model label from the FILENAME (release
# display token) — d["model"] still holds the internal training codename.
for jf in sorted(glob.glob(f"{MX.BASE}/data/raw/region_*.json")):
    d = json.load(open(jf))
    m = os.path.basename(jf)[len("region_"):-len(".json")]
    def pm(k):
        v = [p[k] for p in d.get("perturb", []) if p.get(k) is not None and p.get("task") in CAP]
        return (rnd(float(np.mean(v))), len(v)) if v else (None, 0)
    matched = [x for x in d.get("matched", []) if x.get("task") in CAP]
    mt_in = float(np.mean([_mid(x["attn_in_fg"]) for x in matched])) if matched else None
    mt_cot = float(np.mean([_mid(x["attn_cot_fg"]) for x in matched])) if matched else None
    def share(reg, key):
        a = [_mid(x[key]) for x in d.get("attn", {}).get(reg, []) if x and x.get("task") in CAP]
        return rnd(100 * float(np.mean(a))) if a else None
    dwc, n_pert = pm("d_wrong_cot")
    attn_rows.append({
        "model": m, "n_perturb": n_pert,
        "d_wrong_cot": dwc, "d_syn_cot": pm("d_syn_cot")[0], "d_wrong_input": pm("d_wrong_input")[0],
        "n_matched": len(matched),
        "matched_attn_input_fg": rnd(mt_in), "matched_attn_cot_fg": rnd(mt_cot),
        "matched_ratio_input_over_cot": rnd(mt_in / mt_cot) if (mt_in and mt_cot) else None,
        "pertoken_cot_share_ER0": share("ER0", "pertok"), "pertoken_cot_share_ERpos": share("ERpos", "pertok"),
        "raw_cot_mass_share_ER0": share("ER0", "raw"),
    })
if attn_rows:
    with open(f"{OUT}/attention_perturbation.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(attn_rows[0].keys()))
        w.writeheader()
        w.writerows(attn_rows)

# The two human-validation tables (Human_eval_agreement, Human_eval_extraction) are not
# regenerated here. They are terminal data: the chemist annotation records they were computed
# from are not part of this release, so the tables ship in data/source_data.xlsx as results.
# See data/SOURCE_DATA.md. Nothing downstream reads them from this directory.

